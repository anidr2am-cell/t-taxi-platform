class CallingCountry {
  const CallingCountry(this.code, this.dialCode, this.names);
  final String code;
  final String dialCode;
  final Map<String, String> names;

  String name(String language) => names[language] ?? names['en']!;
  String label(String language) => '${name(language)} ($dialCode)';

  bool matches(String query) {
    final value = query.trim().toLowerCase();
    if (value.isEmpty) return true;
    final aliases = switch (code) {
      'KR' => ['한국', '대한민국', 'korea', 'south korea'],
      'US' => ['usa', 'america'],
      'GB' => ['uk', 'britain'],
      'AE' => ['uae'],
      _ => const <String>[],
    };
    return [
      code,
      dialCode,
      ...names.values,
      ...aliases,
    ].any((part) => part.toLowerCase().contains(value));
  }
}

